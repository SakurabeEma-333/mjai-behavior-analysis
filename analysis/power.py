import math
groups = {
 "你": (664, 771, 6),
 "魂10": (1357, 1651, 10),
 "魂13": (601, 707, 5),
}
print(f"{'组':<6}{'局数':>4}{'决策数':>7}{'一致率':>9}{'标准误':>8}{'95%CI 宽度':>12}")
for k,(h,n,g) in groups.items():
    p = h/n; se = math.sqrt(p*(1-p)/n)
    print(f"{k:<6}{g:>4}{n:>7}{p*100:>8.2f}%{se*100:>7.2f}pp{'±'+format(1.96*se*100,'.2f'):>12}pp")

print("\n两组差异检出的所需样本（80% 功效, p≈0.85, 每局 128 决策）")
for d in (0.02, 0.03, 0.05):
    n = 2*(1.96+0.84)**2*0.85*0.15/(d**2)
    print(f"  分辨 {d*100:.0f}pp 差异 → 每组需 {n:,.0f} 决策 ≈ {n/128:.0f} 局")

print("\n方差(sd)估计的精度（相对误差）")
for g in (5, 10, 15, 20, 40):
    print(f"  {g:>2} 局 → sd 估计误差约 ±{100/math.sqrt(2*(g-1)):.0f}%")
